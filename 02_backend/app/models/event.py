from typing import Any, Literal

from pydantic import BaseModel, Field


class CategoryField(BaseModel):
    key: str = Field(..., min_length=1, description="Stable identifier used in event.metrics")
    label: str = Field(..., min_length=1, description="Display name shown in the app")
    type: Literal["scale", "number", "boolean", "text"]


class Category(BaseModel):
    key: str = Field(..., min_length=1, description="Stable identifier stored in event.type")
    label: str = Field(..., min_length=1, description="Display name shown in the app")
    enabled: bool = True
    fields: list[CategoryField] = Field(default_factory=list)


class EventMeta(BaseModel):
    version: int = 1


class EventIn(BaseModel):
    id: str = Field(..., description="UUID v4 generated by client")
    client_timestamp: str = Field(..., description="ISO 8601 UTC timestamp with Z")
    type: str = Field(..., min_length=1, description="Category key")
    text: str
    metrics: dict[str, Any] = Field(default_factory=dict)
    meta: EventMeta = Field(default_factory=EventMeta)


class EventStored(EventIn):
    received_at: str = Field(..., description="ISO 8601 UTC timestamp with Z, set by server")


class QueryIn(BaseModel):
    question: str


class QueryOut(BaseModel):
    answer: str


class DiaryMeta(BaseModel):
    version: int = 1


class DiaryIn(BaseModel):
    date: str = Field(..., description="YYYY-MM-DD")
    answers: dict[str, Any] = Field(default_factory=dict)


class DiaryOut(BaseModel):
    id: str
    date: str
    answers: dict[str, Any]
    saved_at: str
    meta: DiaryMeta = Field(default_factory=DiaryMeta)


class DiarySummaryOut(BaseModel):
    summary: str


class DiaryParseIn(BaseModel):
    raw_text: str
    questions: list[dict[str, str]]


class DiaryParseOut(BaseModel):
    answers: dict[str, str]


class FeedbackIn(BaseModel):
    type: str = Field(..., description="bug or feature")
    text: str


class FeedbackOut(BaseModel):
    id: str
    type: str
    text: str
    created_at: str
    attachment: str | None = None
    meta: dict = Field(default_factory=lambda: {"version": 1})
